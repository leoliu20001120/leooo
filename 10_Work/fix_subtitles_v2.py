def clean_bgm_tail(text):
    """
    清理视频末尾的BGM噪音文字。
    策略：找到最后一个有意义的句子（包含常见结尾语），然后截断后面的内容。
    """
    # 常见结尾标志
    end_markers = [
        "胜率也是有的",
        "胜利率也是有的",
        "胜率也是有",
        "勝率也是有的",
        "勝利率也是有的",
        "如果你也尝试这套玩法",
        "如果你也嘗試這套玩法",
        "感受下",
        "跟随主播第一视角",
        "跟隨主播第一視角",
        "带领队友取胜",
        "帶領隊友取勝",
        "带领队友拿下胜利",
        "快来评论区分享",
        "快來評論區分享",
    ]
    
    lines = text.split('\n')
    last_meaningful_idx = len(lines) - 1
    
    # 从后往前找最后一个包含结尾标志的行
    for marker in end_markers:
        for i in range(len(lines) - 1, -1, -1):
            if marker in lines[i]:
                # 找到标志后，保留这行，但检查后面是否有重复/噪音
                # 给一些缓冲行（可能有一两行有意义的结尾）
                candidate = i
                # 往后看几行，如果有意义就保留
                for j in range(i + 1, min(i + 4, len(lines))):
                    line = lines[j].strip()
                    if not line:
                        continue
                    # 如果是重复的结尾语，跳过
                    if any(m in line for m in end_markers):
                        candidate = j
                        continue
                    # 如果明显是噪音（英文歌词、繁体乱码、重复行）
                    if is_noise_line(line):
                        break
                    candidate = j
                
                last_meaningful_idx = candidate
                # 截断
                result_lines = lines[:last_meaningful_idx + 1]
                # 清理尾部空行
                while result_lines and not result_lines[-1].strip():
                    result_lines.pop()
                return '\n'.join(result_lines) + '\n'
    
    # 没找到结尾标志，尝试从末尾清理明显噪音
    while last_meaningful_idx > 0 and is_noise_line(lines[last_meaningful_idx].strip()):
        last_meaningful_idx -= 1
    
    if last_meaningful_idx < len(lines) - 1:
        result_lines = lines[:last_meaningful_idx + 1]
        while result_lines and not result_lines[-1].strip():
            result_lines.pop()
        return '\n'.join(result_lines) + '\n'
    
    return text


def is_noise_line(line):
    """判断一行是否是BGM噪音"""
    if not line:
        return True
    
    # 纯英文（歌词）
    if re.match(r'^[a-zA-Z\s\',\.\!\?\-\(\)]+$', line):
        return True
    
    # 以 I'm / I was / I can't 等开头的英文歌词
    if re.match(r"^(I'm|I was|I can't|I just|I tried|I had|But in|Watch|Maybe|See me|No one)", line):
        return True
    
    # 繁体+乱码混合
    # 统计繁体字比例高且含乱码特征
    
    # 纯数字行
    if re.match(r'^[\d\s]+$', line):
        return True
    
    # 极短无意义（1-2个字的行，连续多个可能是噪音）
    if len(line) <= 2 and not any(c in line for c in '全体起立海克斯主播'):
        return True
    
    # 重复行模式（如"鱼"、"阿"、"煮"重复）
    if len(set(line.replace(' ', ''))) <= 2 and len(line) <= 6:
        return True
    
    # 包含特定噪音标记
    noise_patterns = [
        r'^à la',
        r'^tu ',
        r'^我 (mirar|tornera|partir)',
        r'^(quarter-th|scraling|detto|Pastor|aule)',
        r'^Não activate',
        r'makeup$',
        r'^\d+$',
    ]
    for pat in noise_patterns:
        if re.search(pat, line):
            return True
    
    return False


def fix_text(text):
    """对文本执行所有替换"""
    for wrong, correct in sorted_replacements:
        text = text.replace(wrong, correct)
    return text


def remove_heavy_repetition(text):
    """移除严重重复的行（连续相同行超过3次）"""
    lines = text.split('\n')
    result = []
    prev_line = None
    repeat_count = 0
    
    for line in lines:
        stripped = line.strip()
        if stripped == prev_line and stripped:
            repeat_count += 1
            if repeat_count <= 2:  # 最多保留3次
                result.append(line)
        else:
            repeat_count = 0
            result.append(line)
        prev_line = stripped
    
    return '\n'.join(result)


